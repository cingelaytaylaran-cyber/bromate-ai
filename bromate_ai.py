# ----------------------
# Header & Controls
# ----------------------
st.markdown('<div class="header">🧪 BROMATE AI</div>', unsafe_allow_html=True)
st.markdown('<div class="tagline">Your Study & Creative Companion</div>', unsafe_allow_html=True)
st.markdown('<div class="features-bar">✍️ Homework • 🎨 Images • 📊 Slides • 🎬 Videos</div>', unsafe_allow_html=True)

# Sidebar Settings
with st.sidebar:
    st.header("⚙️ Settings")
    API_KEY = st.text_input("OpenAI API Key", type="password", placeholder="Paste your key here...")
    st.caption("Your key is never stored — only used for this session")
    
    if st.button("🔄 Clear Chat History"):
        st.session_state.chat_history = [
            {
                "role": "system",
                "content": """
                You are Bromate AI — a sharp, friendly, and helpful study and creative assistant.
                Help students with homework, essays, explanations, and research in clear, simple language.
                For images: describe clearly and give prompts.
                For slides: create full outlines with titles and bullet points.
                For videos: write scripts, scene descriptions, and simple production steps.
                Keep responses well-structured, accurate, and easy to follow.
                """
            }
        ]
        st.success("Chat cleared! ✅")
        st.rerun()

# ----------------------
# Initialize Client
# ----------------------
client = None
if API_KEY:
    client = OpenAI(api_key=API_KEY)

# ----------------------
# Chat History Setup
# ----------------------
if "chat_history" not in st.session_state:
    st.session_state.chat_history = [
        {
            "role": "system",
            "content": """
            You are Bromate AI — a sharp, friendly, and helpful study and creative assistant.
            Help students with homework, essays, explanations, and research in clear, simple language.
            For images: describe clearly and give prompts.
            For slides: create full outlines with titles and bullet points.
            For videos: write scripts, scene descriptions, and simple production steps.
            Keep responses well-structured, accurate, and easy to follow.
            """
        }
    ]

# Display Messages
for msg in st.session_state.chat_history[1:]:
    with st.chat_message(msg["role"]):
        if msg.get("type") == "image":
            st.image(msg["content"], caption="Generated by Bromate AI")
        else:
            st.write(msg["content"])

# ----------------------
# User Input & Response
# ----------------------
user_prompt = st.chat_input("Ask Bromate AI anything...")

if user_prompt:
    if not client:
        st.error("⚠️ Please enter your OpenAI API key in the sidebar first!")
        st.stop()

    # Save & show user message
    st.session_state.chat_history.append({"role": "user", "content": user_prompt})
    with st.chat_message("user"):
        st.write(user_prompt)

    lower_prompt = user_prompt.lower()

    with st.chat_message("assistant"):
        with st.spinner("Bromate AI is working..."):

            # 🎨 Generate Image
            if any(word in lower_prompt for word in ["image", "picture", "diagram", "illustration", "photo"]):
                try:
                    image_response = client.images.generate(
                        model="dall-e-3",
                        prompt=user_prompt,
                        size="1024x1024",
                        quality="standard",
                        n=1
                    )
                    image_url = image_response.data[0].url
                    st.image(image_url, caption="Here's your image")
                    st.session_state.chat_history.append(
                        {"role": "assistant", "content": image_url, "type": "image"}
                    )
                except Exception as e:
                    err_msg = f"⚠️ Could not generate image: {str(e)}"
                    st.write(err_msg)
                    st.session_state.chat_history.append({"role": "assistant", "content": err_msg})

            # 💬 Text / Homework / Slides / Video Script
            else:
                try:
                    ai_response = client.chat.completions.create(
                        model="gpt-3.5-turbo",
                        messages=st.session_state.chat_history,
                        temperature=0.7
                    )
                    reply_text = ai_response.choices[0].message.content
                    st.write(reply_text)
                    st.session_state.chat_history.append({"role": "assistant", "content": reply_text})
                except Exception as e:
                    st.error(f"⚠️ Error: {str(e)}")